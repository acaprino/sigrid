const check = process.argv.includes('--check')
let missing = 0
let out = '// Generated by scripts/icon-packs.mjs from the packs\' own SVGs (licences in THIRD_PARTY.md). Do not edit by hand.\n\n'
out += '/** A drawing: the side of its square view box and its SVG content. */\nexport type Drawing = readonly [box: number, body: string]\n'

for (const pack of PACKS) {
  const names = Object.keys(pack.icons)
  const ids = names.map((name) => pack.icons[name] + pack.suffix)
  const response = await fetch(`https://api.iconify.design/${pack.prefix}.json?icons=${[...new Set(ids)].join(',')}`)
  if (!response.ok) throw new Error(`${pack.id}: ${response.status}`)
  const data = await response.json()
  const lines = []
  ids.forEach((id, i) => {
    const icon = data.icons?.[id] ?? data.icons?.[data.aliases?.[id]?.parent]
    if (!icon) {
      missing++
      console.error(`missing ${pack.prefix}:${id} (${names[i]})`)
      return
    }
    lines.push(`  ${names[i]}: [${icon.width ?? data.width ?? 16}, ${JSON.stringify(icon.body)}],`)
  })
  out += `\nexport const ${pack.id.toUpperCase()}_DRAWINGS = {\n${lines.join('\n')}\n} as const satisfies Readonly<Record<string, Drawing>>\n`
  await new Promise((done) => setTimeout(done, 1500))
}

if (missing > 0) {
  console.error(`${missing} missing: nothing written`)
  process.exit(1)
}
if (!check) writeFileSync(resolve(here, '../src/icon-packs.generated.ts'), out)
console.log(check ? 'all found' : 'written')
