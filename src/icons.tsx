/**
 * An icon by its meaning, drawn from Sigrid's set. Decorative: the label next to it names the thing, so it is hidden
 * from screen readers. A name Sigrid does not draw (from data) is an empty slot of the same size, so the row keeps its
 * alignment (R6).
 */
export function Icon({ name, className }: { name: IconName | (string & {}); className?: string | undefined }) {
  const Glyph = isIconName(name) ? GLYPHS[name] : undefined
  return (
    <span aria-hidden="true" data-icon={name} className="inline-flex shrink-0">
      {Glyph ? <Glyph className={cn('size-4', className)} /> : <span data-icon-empty="" className={cn('size-4', className)} />}
    </span>
  )
}
