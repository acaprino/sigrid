// Sigrid's icons (R6 of the toolkit's rules): icons are visual anchors for the eye, and Sigrid has one set of its own
// (the owner, 2026-11-23: «Sigrid deve avere un suo unico icon set»), the same in every app: Sigrid Icons, MynaUI's
// drawings and Sigrid's own beside them (the owner, 2026-11-24; `src/internal/sigrid-icons.tsx`), in place of Lucide. A
// component asks for an icon by what it means (`settings`, `delete`), never by the name of a drawing, so a meaning
// keeps its drawing in every app. An icon a function needs that is not among the names is added here, to Sigrid's names, never by an app.
// That binds every app: an app imports no icon. The toolkit's own parts take `Icon` too wherever a name has the
// meaning; a part draws a glyph of the set directly only where `Icon` cannot give the same thing: a glyph no name means
// (the sort arrows of a table, the grip of a row moved by hand, the dot of a radio item, the fit of the graph, the kinds
// of an item, which `kindIcon` hands out as glyphs), or a glyph that holds what `Icon`'s wrapping `<span>`
// would take from it (its own place, `ml-auto` or `absolute`: the submenu's chevron, the search field's magnifier; the
// bar's drag attribute; a `data-slot`; its place in a box that is not a flex box, where the wrapper moves it by a pixel:
// the chevron of a select, the check of a ring, a menu or a list), or a stroke `Icon` does not take (the heavier check
// on a card of the look settings).
// The other packs (Phosphor Duotone, Solar Duotone, Fluent Color, Fluent Emoji Flat, Twemoji), the user's choice of a
// pack and an app's own icons left on 2026-11-23; Lucide left on 2026-11-24.
